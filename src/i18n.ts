const BUNDLES: Record<string, Bundle> = { en: {}, vi: VI, ja: JA };

/**
 * Mã ngôn ngữ ở đây theo ISO 639-1 hai chữ, giống `onewriter.nativeLanguage`.
 * `vscode.env.language` có thể trả về dạng có vùng (`zh-cn`, `pt-br`) nên phải
 * cắt lấy phần đầu trước khi tra bảng.
 */
function currentLocale(): string {
  const setting = vscode.workspace
    .getConfiguration('onewriter')
    .get<string>('uiLanguage', 'auto');

  if (setting !== 'auto') {
    return setting;
  }

  const native = vscode.workspace
    .getConfiguration('onewriter')
    .get<string>('nativeLanguage', 'en');
  if (native in BUNDLES) {
    return native;
  }

  const editorLocale = (vscode.env.language || 'en').split('-')[0];
  return editorLocale in BUNDLES ? editorLocale : 'en';
}

export function t(key: MessageKey, params: Record<string, string | number> = {}): string {
  const bundle = BUNDLES[currentLocale()] ?? {};
  const template = bundle[key] ?? EN[key];
  return template.replace(/\{(\w+)\}/g, (whole, name: string) =>
    name in params ? String(params[name]) : whole,
  );
}

/** Bản dịch gửi sang webview, vì webview không gọi được `t` của extension host. */
export function bundleFor(keys: MessageKey[]): Record<string, string> {
  const out: Record<string, string> = {};
  for (const key of keys) {
    out[key] = t(key);
  }
  return out;
}

export const SUPPORTED_UI_LANGUAGES = Object.keys(BUNDLES);
